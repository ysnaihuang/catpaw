async function bundleDist(cjsConfigCode) {
  fs.mkdirSync(DIST_DIR, { recursive: true });
  fs.writeFileSync(path.join(DIST_DIR, 'package.json'), JSON.stringify({ type: 'commonjs' }, null, 2), 'utf8');
  const distIndex = path.join(DIST_DIR, 'index.js');
  const distIndexMd5 = path.join(DIST_DIR, 'index.js.md5');
  const distConfig = path.join(DIST_DIR, 'index.config.js');
  const distConfigMd5 = path.join(DIST_DIR, 'index.config.js.md5');

  let bundled = false;

  // Try esbuild first if available (used in GitHub Actions)
  try {
    const esbuild = await import('esbuild');
    console.log('[Build] Bundling with esbuild...');
    await esbuild.build({
      entryPoints: [path.join(__dirname, 'src', 'index.js')],
      outfile: distIndex,
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: 'node16',
      minify: true,
      charset: 'utf8',
    });
    bundled = true;
  } catch (_) {
    // Fallback to webpack CLI if installed
  }

  if (!bundled) {
    console.log('[Build] Bundling with webpack...');
    execSync('webpack --config webpack.config.cjs', {
      cwd: __dirname,
      stdio: 'inherit',
    });
    bundled = true;
  }

  // Compute MD5 of dist/index.js (32-char lowercase hex, NO trailing newline)
  const indexBuf = fs.readFileSync(distIndex);
  const indexMd5 = crypto.createHash('md5').update(indexBuf).digest('hex').trim();
  fs.writeFileSync(distIndexMd5, indexMd5, 'utf8');

  // Write dist/index.config.js and dist/index.config.js.md5
  fs.writeFileSync(distConfig, cjsConfigCode, 'utf8');
  const configBuf = fs.readFileSync(distConfig);
  const configMd5 = crypto.createHash('md5').update(configBuf).digest('hex').trim();
  fs.writeFileSync(distConfigMd5, configMd5, 'utf8');

  // Also copy to repository root so both /dist/index.js.md5 and /index.js.md5 work
  fs.copyFileSync(distIndex, path.join(__dirname, 'index.js'));
  fs.copyFileSync(distIndexMd5, path.join(__dirname, 'index.js.md5'));
  fs.copyFileSync(distConfig, path.join(__dirname, 'index.config.js'));
  fs.copyFileSync(distConfigMd5, path.join(__dirname, 'index.config.js.md5'));

  console.log(`[Build] Success!`);
  console.log(`  dist/index.js         (${(indexBuf.length / 1024).toFixed(1)} KB)`);
  console.log(`  dist/index.js.md5     -> ${indexMd5}`);
  console.log(`  dist/index.config.js  (${(configBuf.length / 1024).toFixed(1)} KB)`);
  console.log(`  dist/index.config.js.md5 -> ${configMd5}`);
}

const { cjsConfigCode } = await generateRouterAndConfig();
await bundleDist(cjsConfigCode);
